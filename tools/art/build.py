"""Builds the controller art used in game.

  python tools/art/build.py

1. restyle.py turns the vendored SVGs (sources/) into the Valve line-art style and
   measures every button (tools/art/out/, git-ignored).
2. Each drawing is fitted onto a 1024x512 transparent canvas and written as an
   uncompressed 32-bit TGA to media/controllers/<id>.tga.
3. src/Features/Controllers/Definitions.lua is generated with button anchors in
   canvas coordinates (0..1), so the addon needs no per-controller maths.
"""

import json
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import restyle  # noqa: E402

CANVAS = (1024, 512)
MARGIN = 16
RENDER_W = 2000  # render large, then downscale for clean lines

META = {
    "steamdeck": dict(family="valve", labelStyle="Letters", hidden=["L4", "L5", "R4", "R5", "LPAD", "RPAD", "QAM"]),
    "xbox": dict(family="xbox", labelStyle="Letters", hidden=[]),
    "dualsense": dict(family="playstation", labelStyle="Shapes", hidden=["MUTE"]),
    "switchpro": dict(family="nintendo", labelStyle="Reverse", hidden=[]),
}
ORDER = ["xbox", "dualsense", "switchpro", "steamdeck"]


def fit(img):
    """Scale to fit inside the canvas (minus margin), centred. Returns canvas, (x, y, w, h)."""
    cw, ch = CANVAS[0] - 2 * MARGIN, CANVAS[1] - 2 * MARGIN
    s = min(cw / img.width, ch / img.height)
    w, h = round(img.width * s), round(img.height * s)
    small = img.resize((w, h), Image.LANCZOS)
    canvas = Image.new("RGBA", CANVAS, (0, 0, 0, 0))
    x, y = (CANVAS[0] - w) // 2, (CANVAS[1] - h) // 2
    canvas.alpha_composite(small, (x, y))
    return canvas, (x, y, w, h)


def split_shoulders(anchors):
    """Some sources draw both bumpers as one shape: place each bumper under its
    trigger, at the height of the bumper band."""
    band = anchors.pop("PADSHOULDERS", None)
    if not band:
        return
    for side in ("L", "R"):
        trig = anchors.get(f"PAD{side}TRIGGER")
        if trig and f"PAD{side}SHOULDER" not in anchors:
            anchors[f"PAD{side}SHOULDER"] = dict(x=trig["x"], y=band["y"], w=trig["w"] * 1.4, h=band["h"])


def back_grips(anchors):
    """Steam Deck L4/L5/R4/R5 sit on the back of the grips (outside the front
    drawing): place them at the left/right edges, level with the trackpads."""
    lp, rp = anchors.get("LPAD"), anchors.get("RPAD")
    if not (lp and rp):
        return
    for name, pad, x in (("L4", lp, 0.045), ("L5", lp, 0.045), ("R4", rp, 0.955), ("R5", rp, 0.955)):
        dy = -0.06 if name.endswith("4") else 0.12
        anchors.setdefault(name, dict(x=x, y=pad["y"] + dy, w=0.05, h=0.06))


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_definitions(defs, path):
    out = [
        "-- GENERATED by tools/art/build.py - do not edit by hand.",
        "-- Button anchors are centres/sizes in 0..1 of the 1024x512 texture.",
        "local _, ns = ...",
        "local Register = ns.Controllers.Registry.Register",
        "",
    ]
    for d in defs:
        out.append("Register({")
        for k in ("id", "name", "family", "labelStyle", "texture"):
            out.append(f"    {k} = {lua_str(d[k])},")
        hidden = ", ".join(lua_str(h) for h in d["hidden"])
        out.append(f"    hidden = {{ {hidden} }}," if hidden else "    hidden = {},")  # StyLua's format
        out.append("    anchors = {")
        for b in sorted(d["anchors"]):
            a = d["anchors"][b]
            out.append(
                "        {} = {{ x = {:.4f}, y = {:.4f}, w = {:.4f}, h = {:.4f} }},".format(
                    b, a["x"], a["y"], a["w"], a["h"]
                )
            )
        out.append("    },")
        out.append("})")
        out.append("")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))


def main():
    out_dir = os.path.join(HERE, "out")
    restyle.STYLE = "lineart"
    restyle.OUT_W = RENDER_W
    restyle.main(os.path.join(HERE, "sources"), out_dir)
    with open(os.path.join(out_dir, "anchors.json"), encoding="utf-8") as f:
        measured = json.load(f)

    media = os.path.join(ROOT, "media", "controllers")
    os.makedirs(media, exist_ok=True)
    defs = []
    for cid in ORDER:
        m = measured[cid]
        img = Image.open(os.path.join(out_dir, cid + ".png")).convert("RGBA")
        canvas, (x, y, w, h) = fit(img)
        canvas.save(os.path.join(media, cid + ".tga"))
        anchors = {
            b: dict(
                x=(x + a["cx"] * w) / CANVAS[0],
                y=(y + a["cy"] * h) / CANVAS[1],
                w=a["w"] * w / CANVAS[0],
                h=a["h"] * h / CANVAS[1],
            )
            for b, a in m["anchors"].items()
        }
        split_shoulders(anchors)
        if cid == "steamdeck":
            back_grips(anchors)
        defs.append(
            dict(
                id=cid,
                name=m["name"],
                texture="Interface\\AddOns\\GamepadGrimoire\\media\\controllers\\" + cid,
                anchors=anchors,
                **META[cid],
            )
        )
        print(f"{cid:<10} {len(anchors):2d} anchors -> media/controllers/{cid}.tga")
    write_definitions(defs, os.path.join(ROOT, "src", "Features", "Controllers", "Definitions.lua"))


if __name__ == "__main__":
    main()
