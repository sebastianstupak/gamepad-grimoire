"""Builds the controller art used in game.

  python tools/art/build.py

1. restyle.py turns the vendored SVGs (sources/) into the Valve line-art style and
   measures every button (tools/art/out/, git-ignored).
2. Each drawing is fitted onto a 1024x512 transparent canvas and written as an
   uncompressed 32-bit TGA to media/controllers/<id>.tga.
3. src/Features/Controllers/Definitions.lua is generated with button anchors in
   canvas coordinates (0..1), so the addon needs no per-controller maths.
"""

import json
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import back  # noqa: E402
import restyle  # noqa: E402
import schematic  # noqa: E402

CANVAS = (1024, 512)
MARGIN = 16
RENDER_W = 2000  # render large, then downscale for clean lines

META = {
    "steamdeck": dict(family="valve", labelStyle="Letters", hidden=["LPAD", "RPAD", "QAM", "PADSYSTEM"]),
    "xbox": dict(family="xbox", labelStyle="Letters", hidden=[]),
    "dualsense": dict(family="playstation", labelStyle="Shapes", hidden=["MUTE"]),
    "switchpro": dict(family="nintendo", labelStyle="Reverse", hidden=[]),
    "dualshock4": dict(family="playstation", labelStyle="Shapes", hidden=[]),
    "xbox360": dict(family="xbox", labelStyle="Letters", hidden=[], labels={"PADBACK": "Back", "PADFORWARD": "Start"}),
    "steamcontroller": dict(family="valve", labelStyle="Letters", hidden=[], labels={"PADDPAD": "LPad"}),
    # drawn from a layout description (tools/art/schematic.py): no vector source exists
    "rogally": dict(family="xbox", labelStyle="Letters", hidden=[], labels={"PADSOCIAL": "CC", "PADSYSTEM": "Armoury"}),
    "legiongo": dict(
        family="xbox", labelStyle="Letters", hidden=[], labels={"PADSOCIAL": "Legion L", "PADSYSTEM": "Legion R"}
    ),
    "msiclaw": dict(family="xbox", labelStyle="Letters", hidden=[], labels={"PADSOCIAL": "Quick", "PADSYSTEM": "MSI"}),
    "8bitdo": dict(family="nintendo", labelStyle="Reverse", hidden=[], labels={"PADSOCIAL": "Star"}),
    "generic": dict(family="xbox", labelStyle="Letters", hidden=[], labels={}),
}
ORDER = [
    "xbox",
    "dualsense",
    "switchpro",
    "steamdeck",
    "dualshock4",
    "xbox360",
    "steamcontroller",
    "rogally",
    "legiongo",
    "msiclaw",
    "8bitdo",
    "generic",
]


def fit(img):
    """Scale to fit inside the canvas (minus margin), centred. Returns canvas, (x, y, w, h)."""
    cw, ch = CANVAS[0] - 2 * MARGIN, CANVAS[1] - 2 * MARGIN
    s = min(cw / img.width, ch / img.height)
    w, h = round(img.width * s), round(img.height * s)
    small = img.resize((w, h), Image.LANCZOS)
    canvas = Image.new("RGBA", CANVAS, (0, 0, 0, 0))
    x, y = (CANVAS[0] - w) // 2, (CANVAS[1] - h) // 2
    canvas.alpha_composite(small, (x, y))
    return canvas, (x, y, w, h)


def split_shoulders(anchors):
    """Some sources draw both bumpers as one shape: place each bumper under its
    trigger, at the height of the bumper band."""
    band = anchors.pop("PADSHOULDERS", None)
    if not band:
        return
    for side in ("L", "R"):
        trig = anchors.get(f"PAD{side}TRIGGER")
        if trig and f"PAD{side}SHOULDER" not in anchors:
            anchors[f"PAD{side}SHOULDER"] = dict(x=trig["x"], y=band["y"], w=trig["w"] * 1.4, h=band["h"])


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_definitions(defs, path):
    out = [
        "-- GENERATED by tools/art/build.py - do not edit by hand.",
        "-- Button anchors are centres/sizes in 0..1 of the 1024x512 texture.",
        "local _, ns = ...",
        "local Register = ns.Controllers.Registry.Register",
        "",
    ]
    for d in defs:
        out.append("Register({")
        for k in ("id", "name", "family", "labelStyle", "texture", "view", "front", "back"):
            if k in d:
                out.append(f"    {k} = {lua_str(d[k])},")
        hidden = ", ".join(lua_str(h) for h in d["hidden"])
        out.append(f"    hidden = {{ {hidden} }}," if hidden else "    hidden = {},")  # StyLua's format
        if "labels" in d:
            pairs = ", ".join(f"{b} = {lua_str(t)}" for b, t in sorted(d["labels"].items()))
            out.append(f"    labels = {{ {pairs} }}," if pairs else "    labels = {},")
        out.append("    anchors = {")
        for b in sorted(d["anchors"]):
            a = d["anchors"][b]
            out.append(
                "        {} = {{ x = {:.4f}, y = {:.4f}, w = {:.4f}, h = {:.4f} }},".format(
                    b, a["x"], a["y"], a["w"], a["h"]
                )
            )
        out.append("    },")
        out.append("})")
        out.append("")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))


def main():
    out_dir = os.path.join(HERE, "out")
    restyle.STYLE = "lineart"
    restyle.OUT_W = RENDER_W
    restyle.STROKE_SCALE = 3.0  # shown at ~560 px wide in game: keep lines ~1.5 px
    restyle.main(os.path.join(HERE, "sources"), out_dir)
    with open(os.path.join(out_dir, "anchors.json"), encoding="utf-8") as f:
        measured = json.load(f)

    media = os.path.join(ROOT, "media", "controllers")
    os.makedirs(media, exist_ok=True)
    defs = []
    stroke = max(2, round(RENDER_W / 1000 * 1.5 * 3))
    for cid in ORDER:
        if cid in schematic.LAYOUTS:
            img, drawn = schematic.draw(schematic.LAYOUTS[cid], stroke)
            m = dict(name=schematic.LAYOUTS[cid]["name"], anchors=drawn)
        else:
            m = measured[cid]
            img = Image.open(os.path.join(out_dir, cid + ".png")).convert("RGBA")
        canvas, (x, y, w, h) = fit(img)
        canvas.save(os.path.join(media, cid + ".tga"))
        anchors = {
            b: dict(
                x=(x + a["cx"] * w) / CANVAS[0],
                y=(y + a["cy"] * h) / CANVAS[1],
                w=a["w"] * w / CANVAS[0],
                h=a["h"] * h / CANVAS[1],
            )
            for b, a in m["anchors"].items()
        }
        split_shoulders(anchors)
        tex = "Interface\\AddOns\\GamepadGrimoire\\media\\controllers\\"
        defs.append(dict(id=cid, name=m["name"], texture=tex + cid, back=cid + "_back", anchors=anchors, **META[cid]))
        print(f"{cid:<10} {len(anchors):2d} anchors -> media/controllers/{cid}.tga")

        # back view: same canvas placement, so it lines up with the front
        drawing = {
            b: dict(
                cx=(a["x"] * CANVAS[0] - x) / w,
                cy=(a["y"] * CANVAS[1] - y) / h,
                w=a["w"] * CANVAS[0] / w,
                h=a["h"] * CANVAS[1] / h,
            )
            for b, a in anchors.items()
        }
        bimg, banchors = back.draw(img, drawing, cid, stroke=stroke)
        bcanvas, _ = fit(bimg)
        bcanvas.save(os.path.join(media, cid + "_back.tga"))
        bid = cid + "_back"
        defs.append(
            dict(
                id=bid,
                name=back.SUBTITLE[cid],
                family=META[cid]["family"],
                labelStyle=META[cid]["labelStyle"],
                texture=tex + bid,
                view="back",
                front=cid,
                hidden=[],
                labels=back.labels(cid),
                anchors={
                    b: dict(
                        x=(x + a["cx"] * w) / CANVAS[0],
                        y=(y + a["cy"] * h) / CANVAS[1],
                        w=a["w"] * w / CANVAS[0],
                        h=a["h"] * h / CANVAS[1],
                    )
                    for b, a in banchors.items()
                },
            )
        )
        print(f"{bid:<15} {len(banchors):2d} anchors -> media/controllers/{bid}.tga")
    write_definitions(defs, os.path.join(ROOT, "src", "Features", "Controllers", "Definitions.lua"))
    gallery(os.path.join(ROOT, "docs", "images", "controllers.png"))


def gallery(path, bg=(43, 44, 51)):
    """2x2 sheet of every controller texture on the line-art background (README image)."""
    media = os.path.join(ROOT, "media", "controllers")
    tiles = [Image.open(os.path.join(media, cid + ".tga")).convert("RGBA") for cid in ORDER]
    w, h = CANVAS[0] // 2, CANVAS[1] // 2
    sheet = Image.new("RGB", (2 * w, 2 * h), bg)
    for i, t in enumerate(tiles):
        cell = Image.new("RGBA", CANVAS, (*bg, 255))
        cell.alpha_composite(t)
        sheet.paste(cell.resize((w, h), Image.LANCZOS).convert("RGB"), ((i % 2) * w, (i // 2) * h))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    sheet.save(path, optimize=True)


if __name__ == "__main__":
    main()
